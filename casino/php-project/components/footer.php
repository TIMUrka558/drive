})();

// ── Sidebar open/close ──
function bwSidebarOpen(){
  document.getElementById('bw-sidebar').classList.add('open');
  document.getElementById('bw-sidebar-overlay').classList.add('active');
  var tb = document.getElementById('bw-topbar-user');
  if (tb) tb.style.visibility = 'hidden';
  var tg = document.getElementById('bw-topbar-guest');
  if (tg) tg.style.visibility = 'hidden';
  document.body.style.overflow = 'hidden';
}
function bwSidebarClose(){
  document.getElementById('bw-sidebar').classList.remove('open');
  document.getElementById('bw-sidebar-overlay').classList.remove('active');
  var tb = document.getElementById('bw-topbar-user');
  if (tb) tb.style.visibility = 'visible';
  var tg = document.getElementById('bw-topbar-guest');
  if (tg) tg.style.visibility = 'visible';
  document.body.style.overflow = '';
}
// Закрытие по Escape
document.addEventListener('keydown', function(e){ if(e.key==='Escape') bwSidebarClose(); });

